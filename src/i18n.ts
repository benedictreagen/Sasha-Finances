/**
 * Format a controlled dropdown or enum value into the user's selected language
 * without mutating the underlying data.
 */
export function formatControlledValue(
  _type: 'category' | 'type' | 'purpose' | 'paymentMethod' | 'accountType' | 'event' | 'depositStatus',
  rawValue: string | undefined | null,
  lang: Language
): string {
  if (!rawValue) return '';
  const trimmed = rawValue.trim();
  const match = CONTROLLED_TRANSLATIONS[trimmed];
  if (match) {
    return match[lang] || match.en || rawValue;
  }
  return rawValue;
}
